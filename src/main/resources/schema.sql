CREATE TABLE IF NOT EXISTS app_users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(32) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    privileges INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS albums (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner INTEGER NOT NULL,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT fk_albums_owner FOREIGN KEY (owner) REFERENCES app_users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_albums_owner ON albums(owner);

CREATE TABLE IF NOT EXISTS photos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id INTEGER NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    storage_name VARCHAR(64) NOT NULL UNIQUE,
    content_type VARCHAR(32) NOT NULL,
    description VARCHAR(500) NOT NULL,
    photo_date DATE NOT NULL,
    CONSTRAINT fk_photos_album FOREIGN KEY (album_id) REFERENCES albums(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_photos_album_date ON photos(album_id, photo_date);
